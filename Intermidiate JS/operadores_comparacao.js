/* 
Operadores de comparação:
- > maior que;
- >= maior que ou igual;
- < menor que;
- <= menor que ou igual;
- == igualdade (valor) -> não é recomendado. Sempre use a versão estrita;
- != diferente (valor) -> não é recomendado. Sempre use a versão estrita;
- === igualdade estrita (valor e tipo);
- !== diferente estrito (valor e tipo);
*/
